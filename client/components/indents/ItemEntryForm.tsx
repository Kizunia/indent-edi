"use client";

import { useEffect, useId, useRef, useState } from "react";
import { ApiError, apiFetch, isAborted, toApiError } from "@/lib/client/api";
import type { ItemOption, Meta, StockEntry } from "@/lib/services/types";
import { isValidCalendarDate } from "@/lib/shared/datetime";
import { NOT_AVAILABLE, displayQuantity, isPositiveQuantity } from "@/lib/shared/format";
import ErrorDialog from "@/components/ui/ErrorDialog";
import Field, { describedBy } from "@/components/ui/Field";
import { newLineKey, type DraftLine } from "./draft";
import ItemCombobox from "./ItemCombobox";

type StockState =
  | { status: "idle" }
  | { status: "loading" }
  | { status: "ok"; quantity: string | null }
  | { status: "error" };

const DUPLICATE_MESSAGE = "This item is already in the indent. Edit its quantity instead.";
const ASSIGNED_ON_SAVE = "Assigned on save";
const CODE_HINT = "Generated by the system when the indent is saved.";

// Item entry (FR-04..FR-07, SRS 8.2, 8.3, 8.4, 9.3). Two inputs, Item Name and
// Item Code: picking an existing item from either one fills the other, the
// specification, drawing number, unit and current stock. For a new item the name
// is typed and the code is generated on save (BR-03), so it is shown read-only.
export default function ItemEntryForm({
  meta,
  headerDepartmentId,
  minDate,
  existingItemIds,
  allowDuplicates,
  addLabel = "Add Item",
  busy = false,
  onAdd,
}: {
  meta: Pick<Meta, "departments" | "units">;
  headerDepartmentId: number | null;
  /** Required Date may not be before this (the indent date). */
  minDate: string;
  existingItemIds: number[];
  allowDuplicates: boolean;
  addLabel?: string;
  busy?: boolean;
  /** Return false to keep the entered values (e.g. the user cancelled a confirmation). */
  onAdd: (line: DraftLine) => boolean | void | Promise<boolean | void>;
}) {
  const uid = useId();
  const id = (name: string) => `${uid}-${name}`;

  const [mode, setMode] = useState<"existing" | "new">("existing");
  const [item, setItem] = useState<ItemOption | null>(null);
  const [nameText, setNameText] = useState("");
  const [codeText, setCodeText] = useState("");
  const [specification, setSpecification] = useState("");
  const [drawing, setDrawing] = useState("");
  const [stock, setStock] = useState<StockState>({ status: "idle" });
  const [departmentId, setDepartmentId] = useState(headerDepartmentId ? String(headerDepartmentId) : "");
  const [purpose, setPurpose] = useState("");
  const [quantity, setQuantity] = useState("");
  const [unitId, setUnitId] = useState("");
  const [requiredDate, setRequiredDate] = useState("");
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [dialogError, setDialogError] = useState<ApiError | null>(null);

  const stockAbort = useRef<AbortController>(undefined);
  useEffect(() => () => stockAbort.current?.abort(), []);

  const effectiveDepartment = departmentId || (headerDepartmentId ? String(headerDepartmentId) : "");
  const itemId = item?.id;

  /** Reads the latest stock for one item (SRS 9.4). Resolves to the entry, or null if the lookup failed. */
  async function readStock(forItemId: number, signal?: AbortSignal): Promise<StockEntry | null> {
    try {
      const res = await apiFetch<{ stock: StockEntry[] }>(`/api/stock?itemIds=${forItemId}`, { signal });
      return res.stock[0] ?? { itemId: forItemId, quantity: null, updatedAt: null };
    } catch (err) {
      if (isAborted(err)) return null;
      throw err;
    }
  }

  async function loadStock(forItemId: number, { silent = false } = {}) {
    stockAbort.current?.abort();
    const controller = new AbortController();
    stockAbort.current = controller;
    if (!silent) setStock({ status: "loading" });
    try {
      const entry = await readStock(forItemId, controller.signal);
      if (entry) setStock({ status: "ok", quantity: entry.quantity });
    } catch (err) {
      // Never treated as 0: the value stays "Not available" and the user is told (FR-22, 12.3).
      setStock({ status: "error" });
      if (!silent) setDialogError(toApiError(err));
    }
  }

  // SRS 9.4: do not rely on an old stock value; refresh when the user comes back to the page.
  useEffect(() => {
    if (itemId === undefined) return;
    const onFocus = () => void loadStock(itemId, { silent: true });
    window.addEventListener("focus", onFocus);
    return () => window.removeEventListener("focus", onFocus);
    // loadStock only uses refs and setState, so it is stable for this effect
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [itemId]);

  function clearItem() {
    stockAbort.current?.abort();
    setItem(null);
    setStock({ status: "idle" });
    setErrors((e) => ({ ...e, name: "", code: "" }));
  }

  function pick(option: ItemOption) {
    if (item?.id === option.id) return;
    setItem(option);
    setNameText(option.itemName);
    setCodeText(option.itemCode);
    if (option.defaultUnit) setUnitId(String(option.defaultUnit.id));
    setErrors((e) => ({ ...e, name: "", code: "" }));
    void loadStock(option.id);
  }

  function changeMode(next: "existing" | "new") {
    stockAbort.current?.abort();
    setMode(next);
    setItem(null);
    setNameText("");
    setCodeText("");
    setSpecification("");
    setDrawing("");
    setStock({ status: "idle" });
    setErrors({});
  }

  function reset() {
    stockAbort.current?.abort();
    setItem(null);
    setNameText("");
    setCodeText("");
    setSpecification("");
    setDrawing("");
    setStock({ status: "idle" });
    setPurpose("");
    setQuantity("");
    setUnitId("");
    setRequiredDate("");
    setErrors({});
  }

  async function add() {
    const next: Record<string, string> = {};
    if (mode === "existing") {
      if (!item) {
        if (!nameText.trim() && !codeText.trim()) next.name = "Select an item.";
        else if (codeText.trim()) next.code = "Enter a valid Item Code.";
        else next.name = "Select an item from the list.";
      } else if (!allowDuplicates && existingItemIds.includes(item.id)) {
        next.name = DUPLICATE_MESSAGE;
      }
    } else if (!nameText.trim()) {
      next.name = "Item name is required.";
    }
    if (!effectiveDepartment) next.department = "Select a department.";
    if (!isPositiveQuantity(quantity.trim())) next.quantity = "Enter a quantity greater than 0 (up to 4 decimal places).";
    if (!unitId) next.unit = "Select a unit.";
    if (!requiredDate) next.requiredDate = "Required date is required.";
    else if (!isValidCalendarDate(requiredDate)) next.requiredDate = "Enter a valid required date.";
    else if (requiredDate < minDate) next.requiredDate = "Required date cannot be before the indent date.";
    setErrors(next);
    if (Object.keys(next).length > 0) {
      // FR-22 / 12.3: invalid input is announced in a dialog; the fields stay highlighted.
      setDialogError(new ApiError("VALIDATION_FAILED", "Please correct the highlighted fields.", 400, next));
      return;
    }

    let stockShown: string | null = null;
    if (mode === "existing" && item) {
      // Latest value for the row being added (SRS 9.4). If the lookup fails, say so and keep what was shown.
      stockShown = stock.status === "ok" ? stock.quantity : null;
      try {
        const fresh = await readStock(item.id);
        if (fresh) {
          stockShown = fresh.quantity;
          setStock({ status: "ok", quantity: fresh.quantity });
        }
      } catch (err) {
        setDialogError(toApiError(err));
      }
    }

    const common = {
      key: newLineKey(),
      departmentId: Number(effectiveDepartment),
      purpose,
      requiredQuantity: quantity.trim(),
      requiredUnitId: Number(unitId),
      requiredDate,
    };
    const line: DraftLine =
      mode === "existing" && item
        ? {
            ...common,
            itemId: item.id,
            itemCode: item.itemCode,
            itemName: item.itemName,
            specification: item.specification,
            drawingNumber: item.drawingNumber,
            stock: stockShown,
          }
        : {
            ...common,
            newItem: {
              itemName: nameText.trim(),
              ...(specification.trim() ? { specification: specification.trim() } : {}),
              ...(drawing.trim() ? { drawingNumber: drawing.trim() } : {}),
              defaultUnitId: Number(unitId),
            },
            itemCode: null,
            itemName: nameText.trim(),
            specification: specification.trim() || null,
            drawingNumber: drawing.trim() || null,
            stock: null, // a new item has no stock row (DEC-013)
          };
    if ((await onAdd(line)) !== false) reset();
  }

  const stockUnit = item?.defaultUnit ? (item.defaultUnit.symbol ?? item.defaultUnit.name) : "";
  const stockText =
    mode === "new"
      ? NOT_AVAILABLE
      : stock.status === "idle"
        ? "—"
        : stock.status === "loading"
          ? "Checking…"
          : stock.status === "error"
            ? `${NOT_AVAILABLE} (could not be retrieved)`
            : displayQuantity(stock.quantity);

  return (
    <section className="panel p-4" aria-labelledby={id("title")}>
      <h2 id={id("title")} className="mb-3 text-sm font-bold">
        Add an item
      </h2>

      <fieldset disabled={busy} className="m-0 min-w-0 border-0 p-0">
        <legend className="sr-only">Item details</legend>

        <div className="mb-3 flex gap-4 text-[13px]" role="radiogroup" aria-label="Item source">
          {(["existing", "new"] as const).map((m) => (
            <label key={m} className="flex items-center gap-1.5">
              <input type="radio" name={id("mode")} checked={mode === m} onChange={() => changeMode(m)} />
              {m === "existing" ? "Existing item" : "New item"}
            </label>
          ))}
        </div>

        <div className="grid gap-3 md:grid-cols-2 lg:grid-cols-4">
          {/* Item Name and Item Code: choosing one fills the other (SRS 8.2, 9.3). */}
          <div className="lg:col-span-2">
            {mode === "existing" ? (
              <ItemCombobox
                id={id("name")}
                label="Item Name"
                field="name"
                required
                value={nameText}
                error={errors.name}
                placeholder="Type to search by name…"
                onType={(t) => {
                  setNameText(t);
                  setCodeText("");
                  clearItem();
                }}
                onPick={pick}
              />
            ) : (
              <Field id={id("name")} label="Item Name" required error={errors.name}>
                <input
                  id={id("name")}
                  className="input"
                  value={nameText}
                  maxLength={255}
                  aria-invalid={Boolean(errors.name)}
                  aria-describedby={describedBy(id("name"), errors.name)}
                  onChange={(e) => setNameText(e.target.value)}
                />
              </Field>
            )}
          </div>

          {mode === "existing" ? (
            <ItemCombobox
              id={id("code")}
              label="Item Code"
              field="code"
              required
              value={codeText}
              error={errors.code}
              placeholder="Type to search by code…"
              onType={(t) => {
                setCodeText(t);
                setNameText("");
                clearItem();
              }}
              onPick={pick}
            />
          ) : (
            <Field id={id("code")} label="Item Code" hint={CODE_HINT}>
              <input id={id("code")} className="input mono" readOnly aria-readonly="true" value={ASSIGNED_ON_SAVE} aria-describedby={describedBy(id("code"), undefined, CODE_HINT)} />
            </Field>
          )}

          <Field id={id("dept")} label="Department" required error={errors.department}>
            <select
              id={id("dept")}
              className="input"
              value={effectiveDepartment}
              aria-invalid={Boolean(errors.department)}
              aria-describedby={describedBy(id("dept"), errors.department)}
              onChange={(e) => setDepartmentId(e.target.value)}
            >
              <option value="">Select…</option>
              {meta.departments.map((d) => (
                <option key={d.id} value={d.id}>
                  {d.name}
                </option>
              ))}
            </select>
          </Field>

          {mode === "existing" ? (
            <>
              <Field id={id("spec")} label="Specification">
                <input id={id("spec")} className="input" readOnly value={item?.specification ?? ""} placeholder="—" />
              </Field>
              <Field id={id("drawing")} label="Drawing Number">
                <input id={id("drawing")} className="input" readOnly value={item?.drawingNumber ?? ""} placeholder="—" />
              </Field>
            </>
          ) : (
            <>
              <Field id={id("spec")} label="Specification">
                <input id={id("spec")} className="input" value={specification} onChange={(e) => setSpecification(e.target.value)} />
              </Field>
              <Field id={id("drawing")} label="Drawing Number">
                <input id={id("drawing")} className="input" value={drawing} maxLength={100} onChange={(e) => setDrawing(e.target.value)} />
              </Field>
            </>
          )}

          <Field id={id("qty")} label="Required Quantity" required error={errors.quantity}>
            <input
              id={id("qty")}
              className="input"
              inputMode="decimal"
              value={quantity}
              aria-invalid={Boolean(errors.quantity)}
              aria-describedby={describedBy(id("qty"), errors.quantity)}
              onChange={(e) => setQuantity(e.target.value)}
            />
          </Field>

          <Field id={id("unit")} label="Unit" required error={errors.unit}>
            <select
              id={id("unit")}
              className="input"
              value={unitId}
              aria-invalid={Boolean(errors.unit)}
              aria-describedby={describedBy(id("unit"), errors.unit)}
              onChange={(e) => setUnitId(e.target.value)}
            >
              <option value="">Select…</option>
              {meta.units.map((u) => (
                <option key={u.id} value={u.id}>
                  {u.name}
                </option>
              ))}
            </select>
          </Field>

          <Field id={id("purpose")} label="Purpose" className="md:col-span-2">
            <input id={id("purpose")} className="input" value={purpose} onChange={(e) => setPurpose(e.target.value)} />
          </Field>

          <Field id={id("date")} label="Required Date" required error={errors.requiredDate}>
            <input
              id={id("date")}
              className="input"
              type="date"
              min={minDate}
              value={requiredDate}
              aria-invalid={Boolean(errors.requiredDate)}
              aria-describedby={describedBy(id("date"), errors.requiredDate)}
              onChange={(e) => setRequiredDate(e.target.value)}
            />
          </Field>

          <div>
            <span className="field-label">Current Stock</span>
            <p className="py-1.5 text-[13.5px]" role="status" aria-live="polite">
              {stockText}
              {stock.status === "ok" && stock.quantity !== null && stockUnit ? ` ${stockUnit}` : ""}
            </p>
          </div>
        </div>

        <div className="mt-3">
          <button type="button" className="btn btn-primary" onClick={add}>
            {addLabel}
          </button>
        </div>
      </fieldset>

      <ErrorDialog error={dialogError} onClose={() => setDialogError(null)} />
    </section>
  );
}
